#!/usr/bin/env python3
"""PreToolUse hook: keep my data read-only.

Blocks:
  - Write/Edit/NotebookEdit on anything in data/ (except data/weather.json, which the weather script refreshes)
  - Bash commands that modify files in data/ (redirects, tee, mv, cp, rm, sed -i, python writes, ...)
  - Calendar write tools (create/update/delete/respond to events)
Allows everything else, including writes to plan/ and notes/.

Reads the hook JSON on stdin; prints a deny decision as JSON when blocking.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
ALLOWED_DATA = {DATA / "weather.json"}  # generated by scripts/fetch_weather.py

WRITE_TOOLS = {"Write", "Edit", "MultiEdit", "NotebookEdit"}
# Only calendar/task write tools, e.g. create_event, update_event, delete_event, respond_to_event, create_task.
MCP_WRITE = re.compile(r"^mcp__.+__(create|update|delete|respond_to|move|patch|insert|add|remove)_(event|events|task|tasks|calendar|calendars)\w*$")

BASH_MUTATIONS = [
    r">>?\s*['\"]?\S*data/",
    r"\b(tee|mv|cp|rm|truncate|touch|install|chmod|chown|ln|rsync|dd|shred|unlink)\b[^;&|\n]*\bdata/",
    r"\b(sed|perl)\b[^;&|\n]*\s-\w*i\w*\b[^;&|\n]*data/",
    r"data/[^;&|\n]*\b(write_text|write_bytes|json\.dump|\.write\()",
    r"\b(write_text|write_bytes|json\.dump|\.write\()[^\n]*data/",
    r"open\([^)\n]*data/[^)\n]*['\"][wax]\+?b?['\"]",
]


def deny(reason):
    print(json.dumps({
        "hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "permissionDecision": "deny",
            "permissionDecisionReason": reason,
        }
    }))
    sys.exit(0)


def in_protected_data(path_str, cwd):
    p = Path(path_str)
    if not p.is_absolute():
        p = Path(cwd or ROOT) / p
    p = p.resolve()
    try:
        p.relative_to(DATA)
    except ValueError:
        return False
    return p not in ALLOWED_DATA and p.name != ".gitkeep"


def main():
    try:
        event = json.load(sys.stdin)
    except json.JSONDecodeError:
        sys.exit(0)

    tool = event.get("tool_name", "")
    inp = event.get("tool_input", {}) or {}
    cwd = event.get("cwd")

    if tool in WRITE_TOOLS:
        target = inp.get("file_path") or inp.get("notebook_path") or inp.get("path") or ""
        if target and in_protected_data(target, cwd):
            deny(f"Blocked: {target} is in data/, which is read-only. Suggest the change and I'll make it myself.")

    elif tool == "Bash":
        cmd = (inp.get("command") or "").replace("data/weather.json", "WEATHER")
        if "data/" in cmd:
            for pat in BASH_MUTATIONS:
                if re.search(pat, cmd):
                    deny("Blocked: this command would modify files in data/, which is read-only. "
                         "Reading is fine. Suggest the change and I'll make it myself.")

    elif MCP_WRITE.match(tool):
        deny(f"Blocked: {tool} would change my calendar or tasks. My data is read-only. "
             "Suggest the change instead and I'll make it myself.")

    sys.exit(0)


if __name__ == "__main__":
    main()
